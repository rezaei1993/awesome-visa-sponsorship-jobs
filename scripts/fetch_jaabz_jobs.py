#!/usr/bin/env python3
"""Fetch Jaabz featured jobs and write a daily markdown digest for one focus type."""

from __future__ import annotations

import json
import os
import sys
import urllib.request
from datetime import datetime, timezone

API_URL = os.environ.get("JAABZ_API_URL", "https://jaabz.com/api/featured-jobs")
JOB_TYPE = os.environ.get("JOB_TYPE", "remote").strip().lower()  # remote | visa | relocation
OUTPUT = os.environ.get("OUTPUT_FILE", "DAILY_JOBS.md")
LIMIT = int(os.environ.get("JOB_LIMIT", "15"))
SITE = "https://jaabz.com"

TYPE_META = {
    "remote": {
        "flag": "remote",
        "title": "Daily Remote Tech Jobs from Jaabz",
        "hub": f"{SITE}/jobs/remote",
        "label": "Remote",
    },
    "visa": {
        "flag": "visa_sponsorship",
        "title": "Daily Visa Sponsorship Tech Jobs from Jaabz",
        "hub": f"{SITE}/jobs/visasponsorship",
        "label": "Visa sponsorship",
    },
    "relocation": {
        "flag": "relocation",
        "title": "Daily Relocation Tech Jobs from Jaabz",
        "hub": f"{SITE}/jobs/relocation",
        "label": "Relocation",
    },
}


def fetch_jobs() -> list[dict]:
    req = urllib.request.Request(
        API_URL,
        headers={"User-Agent": "jaabz-awesome-list-bot/1.0 (+https://github.com/rezaei1993)"},
    )
    with urllib.request.urlopen(req, timeout=30) as resp:
        payload = json.loads(resp.read().decode("utf-8"))
    return payload.get("jobs") or []


def abs_url(path: str) -> str:
    if path.startswith("http"):
        return path
    return SITE + (path if path.startswith("/") else "/" + path)


def render(jobs: list[dict], meta: dict) -> str:
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    lines = [
        f"# {meta['title']}",
        "",
        f"_Auto-updated daily from [Jaabz]({SITE}) · last refresh (UTC): **{today}**_",
        "",
        f"Browse more: [{meta['label']} hub]({meta['hub']})",
        "",
        "| Role | Company | Country | Tags | Link |",
        "| --- | --- | --- | --- | --- |",
    ]
    if not jobs:
        lines.append("| _No matching jobs in today's featured feed_ | — | — | — | [Jaabz](%s) |" % SITE)
    else:
        for job in jobs[:LIMIT]:
            title = (job.get("title") or "Untitled").replace("|", "/")
            company = (job.get("company") or "—").replace("|", "/")
            country = (job.get("country") or "—").replace("|", "/")
            tags = []
            if job.get("remote"):
                tags.append("remote")
            if job.get("visa_sponsorship"):
                tags.append("visa")
            if job.get("relocation"):
                tags.append("relocation")
            tag_s = ", ".join(tags) or "—"
            url = abs_url(job.get("url") or "/")
            lines.append(f"| {title} | {company} | {country} | {tag_s} | [Apply]({url}) |")

    lines.extend(
        [
            "",
            "## About this file",
            "",
            "This file is generated by GitHub Actions (`.github/workflows/daily-jaabz-jobs.yml`).",
            "Source API: `GET /api/featured-jobs` on Jaabz, filtered by this repository's focus.",
            "",
            f"Want the full list? See [{meta['hub']}]({meta['hub']}).",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    if JOB_TYPE not in TYPE_META:
        print(f"Unknown JOB_TYPE={JOB_TYPE}", file=sys.stderr)
        return 1
    meta = TYPE_META[JOB_TYPE]
    flag = meta["flag"]
    all_jobs = fetch_jobs()
    matched = [j for j in all_jobs if j.get(flag)]
    # Prefer matches; if empty, keep empty rather than wrong type
    text = render(matched, meta)
    with open(OUTPUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"Wrote {OUTPUT}: {len(matched)}/{len(all_jobs)} jobs for type={JOB_TYPE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
